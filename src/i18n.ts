/**
 * 多语言支持：默认跟随系统语言，也可以在设置页手动指定。
 * 语言下拉框里每个选项用它自己的文字显示（简体中文 / 繁體中文 / English / 日本語 / 한국어）。
 */

export const LANGS = ["zh-CN", "zh-TW", "en", "ja", "ko"] as const;
export type Lang = (typeof LANGS)[number];

/** 设置页语言下拉框：code=system 表示跟随系统 */
export const LANGUAGE_OPTIONS: Array<{ code: string; native: string }> = [
  { code: "system", native: "跟随系统 · Auto" },
  { code: "zh-CN", native: "简体中文" },
  { code: "zh-TW", native: "繁體中文" },
  { code: "en", native: "English" },
  { code: "ja", native: "日本語" },
  { code: "ko", native: "한국어" },
];

/** 把设置值解析成实际语言（system → 看浏览器语言） */
export function resolveLanguage(setting: string): Lang {
  if (setting !== "system") {
    return (LANGS as readonly string[]).includes(setting) ? (setting as Lang) : "zh-CN";
  }
  const nav = (navigator.language || "zh-CN").toLowerCase();
  if (/^zh-(tw|hk|hant|mo)/.test(nav)) return "zh-TW";
  if (nav.startsWith("zh")) return "zh-CN";
  if (nav.startsWith("ja")) return "ja";
  if (nav.startsWith("ko")) return "ko";
  if (nav.startsWith("en")) return "en";
  return "zh-CN";
}

